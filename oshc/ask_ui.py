"""Ask a question: a guardrailed, retrieval-only surface over the verified guide.

Why this page exists and why it looks like this.

The tutor's question in Week 11 was fair: a student with a question in their
head cannot use a fixed topic list. This page accepts the question. What it
does NOT do is write an answer, and that is a design decision rather than an
unfinished feature.

Order of operations, every time, with no exceptions and no cache:
    1. oshc.guardrail.check    boundary filter, before anything is read
    2. oshc.policy_search      BM25 over the hash-verified column excerpts
    3. display                 the excerpt and the original page, as published

No sentence on this page is generated. The consequence is that the worst
outcome of a retrieval miss is an unhelpful excerpt, never an invented
determination about someone's cover. That bound is what lets the question box
ship while oshc.composer, which would write prose, stays behind the
refusal-recall gate in oshc.config.REFUSAL_RECALL_FLOOR.

Measured, not assumed. scripts/evaluate_ask_retrieval.py scores this exact
path and writes docs/prototype/ask_ui_check.json. The numbers are quoted in
the "How well does this work" panel below, including where they are weakest.

Question text is never written to disk, to a log or to a provider. The
counters here live in st.session_state and die with the browser tab.

Owner: Bikram Bhattarai. Reviewer: Aayush Khade.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import streamlit as st

from oshc.config import REFUSAL_RECALL_FLOOR
from oshc.guardrail import REFUSAL_TEXT, check
from oshc.navigator_ui import load_source, page_png
from oshc.policy_search import PolicySearch
from oshc.policy_source import CAPTURED_ON, SOURCE_DOC, SOURCE_URL, SourceError
from oshc.schemas import GuardrailVerdict

ROOT = Path(__file__).resolve().parents[1]
MAX_QUESTION_CHARS = 300
RESULT_COUNT = 5

# Session keys this page writes other than the text box itself. Every one holds
# a count, never text. tests/test_ask_ui.py asserts that.
SESSION_KEYS: tuple[str, ...] = ("ask_answered", "ask_refusals")

# Starter questions. Every one is in data/probes/ask_dev_probes.csv and was
# scored by scripts/evaluate_ask_retrieval.py, so nothing offered here is
# untested. Phrasing is deliberately the student's, not the guide's.
STARTERS: tuple[str, ...] = (
    "How do I claim money back after seeing a doctor?",
    "Do I have to wait before I can use my cover?",
    "What is not covered at all?",
    "What about prescriptions and medicine?",
    "How do I get my membership card?",
    "Can my husband be on my policy?",
)

# The page states its own accuracy by reading the recorded report rather than
# carrying numbers in source, so the two can never drift apart. Regenerated by
# scripts/prototype_check_ask_ui.py.
REPORT_PATH = ROOT / "docs" / "prototype" / "ask_ui_check.json"

SCOPE = (
    "This page finds passages in the saved Medibank OSHC Member Guide that match your "
    "words, and shows you the original page. It does not write an answer, and it cannot "
    "tell you what your own policy will pay."
)

VERDICT_HEADING: dict[GuardrailVerdict, str] = {
    GuardrailVerdict.ESCALATE_EMERGENCY: "This needs a person, not a prototype",
    GuardrailVerdict.REFUSE_CLINICAL: "This is a health question",
    GuardrailVerdict.REFUSE_ADVICE: "This asks what your own policy will pay",
}


def _apply_starter() -> None:
    """Move a clicked starter into the box.

    Streamlit refuses a write to a widget's own session key once that widget
    has been created on this run, so this has to happen before the text input
    is rendered, not when the question is read. A starter click therefore sets
    ask_starter and reruns, and the next run lands here first.
    """
    starter = st.session_state.pop("ask_starter", None)
    if isinstance(starter, str) and starter.strip():
        st.session_state["ask_box"] = starter


def _question() -> str:
    """Read the box. Call only after the text input has been rendered."""
    raw = st.session_state.get("ask_box") or ""
    return raw.strip()[:MAX_QUESTION_CHARS] if isinstance(raw, str) else ""


@st.cache_data(show_spinner=False)
def _measured(path: str, mtime: float) -> dict | None:
    """Read the recorded check. mtime is in the cache key so edits are picked up."""
    try:
        record = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    try:
        return {
            "checked": record["checked_at_utc"][:10],
            "gold": record["gold_guide_wording"],
            "dev": record["dev_student_wording"],
            "gap": record["recall_at_5_gap"],
        }
    except (KeyError, TypeError):
        return None


def _report() -> dict | None:
    try:
        return _measured(str(REPORT_PATH), REPORT_PATH.stat().st_mtime)
    except OSError:
        return None


def _page_of(hit) -> int:
    """PolicySearch writes section as 'PDF page N, <column> column'."""
    try:
        return int(hit.section.split()[2].rstrip(","))
    except (AttributeError, IndexError, ValueError):
        return 0


def _count(name: str) -> None:
    """Session-only tally. Never the question text, never written to disk."""
    st.session_state[name] = st.session_state.get(name, 0) + 1


def _blocked(decision, question: str, corpus, raw: bytes) -> None:
    """Show the refusal, then show the reason. The reason is the point."""
    _count("ask_refusals")
    st.error(f"**{VERDICT_HEADING[decision.verdict]}**\n\n{REFUSAL_TEXT[decision.verdict]}")

    if decision.verdict is GuardrailVerdict.ESCALATE_EMERGENCY:
        _emergency_followup(question, corpus, raw)

    with st.expander("Why this prototype stopped here"):
        st.write(
            "The boundary filter runs before any search. It read your question, matched a "
            "rule, and returned a refusal instead of a result. Nothing was looked up."
        )
        st.table({
            "Decision": [decision.verdict.value],
            "Layer": [decision.layer],
            "Matched on": [decision.trigger or "not recorded"],
        })
        if decision.verdict is GuardrailVerdict.ESCALATE_EMERGENCY:
            st.caption(
                "The emergency word list is deliberately wide, so it also stops ordinary "
                "questions that happen to contain one of its words. Asking when ambulance "
                "treatment is covered is refused here, even though that is one of "
                "Navigator's six prepared topics and the guide answers it on page 25. We "
                "keep the list wide on purpose: a missed emergency is worse than a refused "
                "question. Across both probe sets the cost is 2 refusals in 40 questions."
            )


def _emergency_followup(question: str, corpus, raw: bytes) -> None:
    """Offer the document only after the escalation, and only if the user asks for it.

    The escalation above is unconditional and unchanged. This adds nothing to it
    and removes nothing from it: oshc.guardrail still returns the same verdict on
    the same input, so the pending held-out refusal-recall measurement still
    measures the gate as it actually stands. What changes is only what the page
    offers afterwards, and the user decides whether that applies to them.

    Advice and clinical refusals get no equivalent. "Will my policy pay" cannot
    be answered by a document at all, and a symptom must not be, so for those two
    there is nothing honest to offer.
    """
    with st.expander("If you were asking how this is covered, rather than asking for help now"):
        st.caption(
            "Call 000 first if this is happening now. The guide below is general "
            "information about how a service is paid for. It is not help in an emergency."
        )
        hits = PolicySearch(corpus).search(question, k=2)
        if not hits:
            st.write("The saved guide has no passage matching those words.")
            return
        for hit in hits:
            page = _page_of(hit)
            st.markdown(f"**{hit.section}**")
            st.text(hit.text[:700] + ("\n[...]" if len(hit.text) > 700 else ""))
            st.markdown(f"[Open the publisher's PDF at page {page}]({SOURCE_URL}#page={page})")


def _results(question: str, corpus, raw: bytes) -> None:
    hits = PolicySearch(corpus).search(question, k=RESULT_COUNT)
    if not hits:
        st.warning(
            "No passage in the saved guide shares enough wording with that question. "
            "Try the words the guide itself uses, or browse the guide in Navigator."
        )
        return

    _count("ask_answered")
    st.success(f"{len(hits)} passages in the guide mention what you asked about.")
    st.caption(
        "Ordered by word overlap, which is not confidence and not correctness. The first "
        "result is the right one about half the time, so read more than one."
    )

    for hit in hits:
        page = _page_of(hit)
        with st.container(border=True):
            head, badge = st.columns([5, 1])
            head.markdown(f"**{hit.section}**")
            badge.markdown(f"`match {hit.rank} of {len(hits)}`")
            st.text(hit.text[:1200] + ("\n[...]" if len(hit.text) > 1200 else ""))
            left, right = st.columns([1, 1])
            with left:
                st.caption(f"{SOURCE_DOC} | saved {hit.captured_on}")
                st.markdown(f"[Open the publisher's PDF at page {page}]({SOURCE_URL}#page={page})")
            with right:
                if page and st.button("Read this page in Navigator", key=f"ask_goto_{hit.chunk_id}"):
                    st.session_state["nv_requested_page"] = page
                    st.switch_page("pages/2_Navigator.py")
            with st.expander(f"Show the original page {page}"):
                try:
                    st.image(
                        page_png(raw, page),
                        width="stretch",
                        caption=f"Saved guide: physical PDF page {page} of 37",
                    )
                except SourceError:
                    st.caption("The original page could not be rendered.")

    st.info(
        "A passage is not a decision. Conditions often continue in the next column or on "
        "another page, and the guide is one document, not your policy. Medibank confirms "
        "what you are actually covered for."
    )


def _honesty_panel() -> None:
    with st.expander("How well does this work, and where does it fail"):
        measured = _report()
        if measured is None:
            st.warning(
                "No recorded check was found, so this page cannot state its own accuracy. "
                "Run scripts/prototype_check_ask_ui.py before relying on anything here."
            )
            return

        gold, dev = measured["gold"], measured["dev"]
        st.caption(
            f"Measured on this exact code path and recorded on {measured['checked']}. "
            "Regenerate with scripts/prototype_check_ask_ui.py."
        )
        st.table({
            "Probe set": ["Project gold set, guide wording", "Dev probes, student wording"],
            "Questions scored": [gold["allowed_and_scored"], dev["allowed_and_scored"]],
            "Right page in top 5": [f"{gold['recall_at_5']:.0%}", f"{dev['recall_at_5']:.0%}"],
            "Right page ranked first": [f"{gold['recall_at_1']:.0%}", f"{dev['recall_at_1']:.0%}"],
            "Refused at the boundary": [gold["refused_at_guardrail"], dev["refused_at_guardrail"]],
        })
        st.write(
            f"**The gap between those two rows is the finding.** Ask the guide its own "
            f"question and the right page is in the top five {gold['recall_at_5']:.0%} of the "
            f"time. Ask it the way a student asks and that falls to {dev['recall_at_5']:.0%}, "
            f"a drop of {measured['gap']:.0%}. Word-overlap search rewards people who already "
            f"know the vocabulary, which is the opposite of who needs the help."
        )
        st.write("Three failures we can name:")
        st.markdown(
            "- *What is a gap payment* lands on the premium pages, because the guide uses "
            "the word gap for two unrelated things.\n"
            "- Vague questions such as *where do I go if I am sick on the weekend* land in "
            "the glossary, which matches a little of everything.\n"
            "- A question sharing no words with the answer returns nothing useful at all."
        )
        refused = gold["refused_at_guardrail"] + dev["refused_at_guardrail"]
        total = gold["probes"] + dev["probes"]
        st.write(
            f"**The cost of the safety gate, measured.** {refused} of {total} probe questions "
            "were refused before any search ran, both of them general-information questions "
            "that the guide does answer. Asking when ambulance treatment is covered is one of "
            "them, even though that is a prepared Navigator topic. We keep the emergency word "
            "list wide on purpose, and this is the price."
        )
        st.caption(
            "Both probe sets were written and labelled in-house, so neither is held out and "
            f"{dev['recall_at_5']:.0%} is the optimistic end. Neither set measures whether a "
            "student then understood the passage."
        )
        st.write(
            f"**Why there is no written answer here.** Composing prose is the part that can "
            f"state something the guide does not say. Under our architecture plan that "
            f"surface does not ship until refusal recall on the held-out probe set reaches "
            f"{REFUSAL_RECALL_FLOOR:.0%}. That run has not happened, so the composer is not "
            f"reachable from this page. Showing you the passage is what we can defend today."
        )


def render():
    st.title("Ask a question")
    st.caption("Your words, the guide's answer, the original page")

    if os.getenv("OSHC_OFFLINE") != "1" or os.getenv("OSHC_ENABLE_LIVE") != "0":
        st.error("Start this prototype in offline mode before asking a question.")
        return

    st.info(SCOPE)
    try:
        corpus, raw = load_source(ROOT)
    except SourceError:
        st.error("The saved guide could not be verified. Restore the frozen source first.")
        return

    st.caption(f"Medibank OSHC Member Guide | Effective May 2026 | Saved {CAPTURED_ON}")

    _apply_starter()
    st.write("**Start with one of these, or type your own.**")
    columns = st.columns(3)
    for index, starter in enumerate(STARTERS):
        if columns[index % 3].button(starter, key=f"ask_s{index}", width="stretch"):
            st.session_state["ask_starter"] = starter
            st.rerun()

    st.text_input(
        "Your question",
        key="ask_box",
        max_chars=MAX_QUESTION_CHARS,
        placeholder="for example, do I have to wait before I can use my cover?",
    )
    question = _question()

    if not question:
        st.caption(
            "Nothing is sent anywhere. Your question is matched against the saved guide on "
            "this machine and is not stored, logged or sent to any provider."
        )
        _honesty_panel()
        return

    decision = check(question)
    try:
        if decision.blocked:
            _blocked(decision, question, corpus, raw)
        else:
            _results(question, corpus, raw)
    except SourceError:
        st.error("The saved guide became unreadable. Restore the frozen source first.")

    asked = st.session_state.get("ask_answered", 0)
    refused = st.session_state.get("ask_refusals", 0)
    if asked or refused:
        st.caption(
            f"This browser session: {asked} searched, {refused} refused at the boundary. "
            "Counts only. No question text is kept."
        )
    _honesty_panel()
